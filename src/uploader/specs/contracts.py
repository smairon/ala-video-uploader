"""Ports used across module boundaries."""

from pathlib import Path
from typing import Protocol, Self

from uploader.specs.models import MediaPlaylist


class ObjectStorageContract(Protocol):
    async def upload_file(
        self, *, key: str, path: Path, content_type: str, cache_control: str
    ) -> str: ...


class StateStoreContract(Protocol):
    def register_stream(
        self, *, stream_id: str, first_segment_at: float, playlist_seen_at: float
    ) -> None: ...
    def uploaded_uris(self, stream_id: str) -> set[str]: ...
    def mark_uploaded(self, *, stream_id: str, uri: str, etag: str, uploaded_at: float) -> None: ...
    def stream_metadata(self, stream_id: str) -> tuple[float, float, float | None]: ...
    def mark_finalized(self, *, stream_id: str, finalized_at: float) -> None: ...
    def finalized_stream_ids(self) -> set[str]: ...
    def expired_finalized_stream_ids(self, *, before: float) -> set[str]: ...
    def observe_segment(
        self,
        *,
        stream_id: str,
        uri: str,
        size_bytes: int,
        modified_at: float,
        observed_at: float,
    ) -> float: ...
    def published_playlist_hash(self, stream_id: str) -> str | None: ...
    def mark_playlist_published(
        self, *, stream_id: str, content_hash: str, published_at: float
    ) -> None: ...


class PlaylistCodecContract(Protocol):
    def parse(self, text: str) -> MediaPlaylist: ...
    def render(
        self, playlist: MediaPlaylist, published_uris: set[str], *, finalized: bool
    ) -> str: ...


class StreamUploaderContract(Protocol):
    async def publish_stream(self, stream_dir: Path) -> None: ...


class StreamCleanerContract(Protocol):
    def cleanup_stream(self, stream_dir: Path, *, now: float) -> None: ...


class LabelledMetricContract(Protocol):
    def labels(self, *values: str) -> Self: ...
    def inc(self, amount: float = 1) -> None: ...
    def observe(self, amount: float) -> None: ...
    def set(self, value: float) -> None: ...


class MetricsContract(Protocol):
    @property
    def uploads(self) -> LabelledMetricContract: ...
    @property
    def upload_duration(self) -> LabelledMetricContract: ...
    @property
    def uploaded_bytes(self) -> LabelledMetricContract: ...
    @property
    def pending_segments(self) -> LabelledMetricContract: ...
    @property
    def oldest_pending_seconds(self) -> LabelledMetricContract: ...
    @property
    def deleted_files(self) -> LabelledMetricContract: ...
    @property
    def stream_processing_errors(self) -> LabelledMetricContract: ...
    @property
    def streams(self) -> LabelledMetricContract: ...
